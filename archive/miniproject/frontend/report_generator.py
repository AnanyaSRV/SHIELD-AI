
import re
import streamlit as st
import math

def _format_report(report):
    """
    Convert the existing plain-text investigation report into readable
    Markdown without changing its underlying findings.
    """
    if not report:
        return ""

    text = str(report).replace("\r\n", "\n").replace("\r", "\n").strip()

    # Handle reports that have been flattened into one long line.
    # The report agent uses separator lines around its title.
    text = re.sub(
        r"\s*={8,}\s*SHIELD-AI INVESTIGATION REPORT\s*={8,}\s*",
        "\n\n# SHIELD-AI Investigation Report\n\n",
        text,
        flags=re.IGNORECASE,
    )

    # Add line breaks before known report sections if they were flattened.
    section_patterns = [
        (r"\s+GRAPH INVESTIGATION\s*", "\n\n## Graph Investigation\n\n"),
        (r"\s+EVIDENCE\s*", "\n\n## Evidence\n\n"),
        (r"\s+RECOMMENDED ACTION\s*:\s*", "\n\n## Recommended Action\n\n**"),
        (r"\s+Note\s*:\s*", "\n\n## Interpretation and Limitations\n\n"),
    ]

    for pattern, replacement in section_patterns:
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)

    # Convert common report fields into readable Markdown bullets.
    field_patterns = [
        r"Model prediction:",
        r"Fraud probability:",
        r"Decision threshold:",
        r"Classification threshold:",
        r"Threshold status:",
        r"Status:",
        r"Hub detected:",
        r"Fraud ring detected:",
        r"Suspicious neighbors:",
        r"Shared-card proxy neighbors:",
    ]

    for pattern in field_patterns:
        text = re.sub(
            rf"(?<!\n)(?<!^)\s+({pattern})",
            r"\n- **\1**",
            text,
            flags=re.IGNORECASE,
        )

    # Preserve existing evidence bullets and make separator remnants harmless.
    text = re.sub(r"(?m)^\s*={8,}\s*$", "", text)
    text = re.sub(r"(?m)^\s*-\s*", "- ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)

    # Add a caution when the report contains graph proxy information.
    if (
        "shared-card proxy" in text.lower()
        and "graph limitation" not in text.lower()
    ):
        text += (
            "\n\n> **Graph limitation:** Shared-card proxy relationships "
            "are exploratory. They do not independently confirm account "
            "ownership, coordinated fraud, or a fraud ring."
        )

    return text.strip()


def render_report_generator():
    st.header("Case Report")
    st.caption(
        "View and download the report generated by the latest "
        "SHIELD-AI investigation."
    )

    result = st.session_state.get("shield_ai_last_result")

    if not result:
        st.info(
            "No investigation report is available yet. "
            "Go to Fraud Detection and investigate a transaction first."
        )
        return

    risk = result.get("risk_result") or {}
    probability = risk.get("fraud_probability")
    prediction = risk.get("prediction", "Not available")
    action = result.get("action", "Not available")
    report = result.get("report", "")

    col1, col2, col3 = st.columns(3)

    try:
        probability_value = float(probability)
        if math.isfinite(probability_value) and 0 <= probability_value <= 1:
            probability_display = f"{probability_value:.2%}"
        else:
            probability_display = "N/A"
    except (TypeError, ValueError):
        probability_display = "N/A"

    col1.metric("Fraud probability", probability_display)
    col2.metric("Prediction", str(prediction))
    col3.metric("Recommended action", str(action))

    threshold = risk.get("threshold")
    try:
        probability_value = float(probability)

        if math.isfinite(probability_value) and 0 <= probability_value <= 1:
            probability_display = f"{probability_value:.2%}"
        else:
            probability_display = "N/A"

    except (TypeError, ValueError):
        probability_display = "N/A"

    st.divider()
    st.subheader("Investigation Report")

    if not report:
        st.warning(
            "No report text was returned. Investigate the transaction again."
        )
        return

    formatted_report = _format_report(report)

    # Render headings, lists, and paragraphs instead of a code block.
    st.markdown(formatted_report)

    st.download_button(
        label="Download Case Report",
        data=formatted_report,
        file_name="SHIELD_AI_Case_Report.md",
        mime="text/markdown",
        type="primary",
        key="download_shield_ai_case_report",
    )

    st.caption(
        "This report contains model-assisted findings. A fraud prediction "
        "is not a confirmed finding of fraudulent activity. Graph proxy "
        "relationships should not be treated as verified fraud evidence."
    )


render_report_generator()
